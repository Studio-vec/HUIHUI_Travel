export const FLOWER_PATH = (() => {
  /* 위로 뻗은 꽃잎 한 장을 72°씩 돌려 다섯 장을 만든다 */
  const petal: [number, number][] = [[0, -1.8], [-5, -4], [-4.6, -10.5], [0, -10.5], [4.6, -10.5], [5, -4], [0, -1.8]];
  const f = (n: number) => +n.toFixed(2);
  const petals = [0, 1, 2, 3, 4].map((k) => {
    const a = (k * 72 * Math.PI) / 180, c = Math.cos(a), s = Math.sin(a);
    const p = petal.map(([x, y]) => `${f(x * c - y * s)} ${f(x * s + y * c)}`);
    return `M${p[0]}C${p[1]} ${p[2]} ${p[3]}C${p[4]} ${p[5]} ${p[6]}Z`;
  });
  return petals.join('') + 'M1.6 0A1.6 1.6 0 1 1 -1.6 0A1.6 1.6 0 1 1 1.6 0Z';
})();
